        public fun current(osArch: String = System.getProperty("os.arch") ?: ""): Arch =
            when (osArch) {
                "amd64", "x86_64" -> AMD64
                "aarch64", "arm64" -> AARCH64
                else -> throw UnsupportedOperationException("Architecture not supported: $osArch")
            }

        public fun fromAudit(audit: Int): Arch =
            when (audit) {
                AUDIT_ARCH_X86_64 -> AMD64
                AUDIT_ARCH_AARCH64 -> AARCH64
                else -> throw UnsupportedOperationException("Audit architecture not supported: $audit")
            }
    }

    internal fun isSimpleDescriptorCreatingSyscall(nr: Long): Boolean {
        val num = nr.toInt()
        return num == open ||
            num == openat ||
            num == openat2 ||
            num == socket ||
            num == memfdCreate ||
            num == pidfdOpen ||
            num == pidfdGetFd ||
            num == accept ||
            num == accept4 ||
            num == userfaultfd ||
            num == bpf ||
            num == ioUringSetup
    }
